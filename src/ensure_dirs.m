function ensure_dirs(P)
%ENSURE_DIRS  建立生成目录，并把 Simulink 的缓存/代码目录重定向到 results/。
%   否则 Simulink 会在工程根目录留下 slprj/ 和 *.slxc，污染工作区。

dirs = {P.modelDir, ...
        P.outDir, ...
        fullfile(P.outDir, 'cache'), ...
        fullfile(P.outDir, 'codegen'), ...
        fullfile(P.outDir, 'figures')};
for k = 1:numel(dirs)
    if ~isfolder(dirs{k}), mkdir(dirs{k}); end
end

Simulink.fileGenControl('set', ...
    'CacheFolder',    fullfile(P.outDir, 'cache'), ...
    'CodeGenFolder',  fullfile(P.outDir, 'codegen'));
end
